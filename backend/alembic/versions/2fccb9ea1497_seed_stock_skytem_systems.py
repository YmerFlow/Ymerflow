def upgrade() -> None:
    conn = op.get_bind()
    existing = {r[0] for r in conn.execute(
        sa.select(_systems.c.name).where(_systems.c.project_id.is_(None))
    )}
    for name, _source, b64 in _STOCK_SYSTEMS:
        if name in existing:
            continue
        conn.execute(_systems.insert().values(
            id=str(uuid.uuid4()),
            name=name,
            gex=base64.b64decode(b64),
            project_id=None,
            is_public=True,
            created_at=datetime.utcnow(),
        ))


def downgrade() -> None:
    """Remove only the rows this migration inserted.

    Matching on name alone would also delete a same-named system that existed
    before this migration ran - which upgrade() deliberately left in place.
    Matching on name AND the exact payload removes just our own rows.
    """
    conn = op.get_bind()
    for name, _source, b64 in _STOCK_SYSTEMS:
        conn.execute(_systems.delete().where(sa.and_(
            _systems.c.project_id.is_(None),
            _systems.c.name == name,
            _systems.c.gex == base64.b64decode(b64),
        )))
